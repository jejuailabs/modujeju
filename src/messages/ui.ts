const numberLocales: Record<Locale, string> = {
  ko: "ko-KR",
  en: "en-US",
  zh: "zh-CN",
  ja: "ja-JP",
};

export function priceLabel(place: Place, locale: Locale): string {
  const text = copy(locale);
  const amount = place.price.amount;
  if (amount === null || !Number.isFinite(amount) || amount < 0)
    return text.priceUnknown;
  if (amount === 0) return text.free;
  const unit = {
    person: text.perPerson,
    drink: text.perDrink,
    night: text.perNight,
  }[place.price.unit];
  const formatted = new Intl.NumberFormat(numberLocales[locale] ?? "ko-KR", {
    style: "currency",
    currency: "KRW",
    currencyDisplay: "narrowSymbol",
    maximumFractionDigits: 0,
  }).format(amount);
  return `${formatted} / ${unit}`;
}
