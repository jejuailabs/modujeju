export const accountMessages: Record<Locale, Messages> = { ko, en, zh, ja };
export function accountError(code: string, locale: Locale): string {
  const c = accountMessages[locale];
  if (
    ["CLOUD_DISABLED", "SERVER_CONFIGURATION", "SESSION_FAILED"].includes(code)
  )
    return c.unavailable;
  if (["UNAUTHORIZED", "INVALID_TOKEN", "RECENT_LOGIN_REQUIRED"].includes(code))
    return c.loginRequired;
  if (code === "FORBIDDEN") return c.forbidden;
  if (code === "IN_APP_BROWSER") return c.inApp;
  if (code === "ORIGIN_DENIED") return c.denied;
  if (code.startsWith("VISITJEJU_")) return c.sourceDisabled;
  if (code === "EDIT_CONFLICT" || code === "PLACE_EXISTS") return c.conflict;
  if (
    [
      "INVALID_INPUT",
      "PUBLICATION_INCOMPLETE",
      "IMAGE_RIGHTS_REQUIRED",
      "VERIFICATION_REQUIRED",
      "INVALID_PLACEHOLDER",
      "PLACE_NOT_OPEN",
    ].includes(code)
  )
    return c.invalidInput;
  if (code === "SOURCE_NOT_FOUND") return c.invalidRecord;
  if (code === "RATE_LIMITED") return c.limited;
  return c.failed;
}
