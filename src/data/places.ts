const demoFact = <T>(value: T): Fact<T> => ({
  value,
  source: "demo",
  verifiedAt: null,
});

/** Entirely fictional fixtures. Coordinates indicate an approximate region, never a visitable business. */
function facts(values: Partial<FactValues> = {}): PlaceFacts {
  return Object.fromEntries(
    Object.entries({ ...defaultValues, ...values }).map(([key, value]) => [
      key,
      demoFact(value),
    ]),
  ) as unknown as PlaceFacts;
}

